<?php

namespace App\Http\Controllers;

use Barryvdh\DomPDF\Facade\Pdf;
use App\Models\AuditLog;
use App\Models\User;
use Illuminate\Http\Request;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Response as ResponseFacade;
use Illuminate\View\View;
use Symfony\Component\HttpFoundation\Response;

class ReportController extends Controller
{
    public function index(Request $request): View
    {
        $request->validate($this->filterRules($request));
        $users = $this->filteredUsers($request)->paginate(30)->withQueryString();
        $roles = DB::table('roles')->orderBy('display_name')->pluck('name');

        return view('reports.index', compact('users', 'roles'));
    }

    public function export(Request $request, string $format): Response
    {
        abort_unless(in_array($format, ['csv', 'pdf', 'xlsx'], true), 404);
        $request->validate($this->filterRules($request));
        $users = $this->filteredUsers($request)->get();
        AuditLog::record('transaction', 'Generated user report in '.$format.' format.', $request->user());

        if ($format === 'csv') {
            return ResponseFacade::streamDownload(function () use ($users, $request): void {
                $handle = fopen('php://output', 'w');
                fputcsv($handle, ['User report']);
                fputcsv($handle, ['Generated at', now()->format('Y-m-d H:i:s')]);
                fputcsv($handle, ['Generated by', $this->safeCsvCell($request->user()?->name)]);
                fputcsv($handle, ['Name', 'Email', 'Department', 'Role', 'Status', 'Created']);
                foreach ($users as $user) {
                    fputcsv($handle, array_map($this->safeCsvCell(...), [
                        $user->name,
                        $user->email,
                        $user->department,
                        $user->role,
                        $user->status,
                        $user->created_at?->format('Y-m-d'),
                    ]));
                }
                fclose($handle);
            }, 'user-report.csv', ['Content-Type' => 'text/csv; charset=UTF-8']);
        }

        if ($format === 'xlsx') {
            return $this->xlsxResponse($users, $request);
        }

        return Pdf::loadView('reports.print', [
            'users' => $users,
            'generatedAt' => now(),
            'generatedBy' => $request->user()?->name,
        ])->setPaper('a4', 'landscape')->download('user-report.pdf');
    }

    private function xlsxResponse($users, Request $request): Response
    {
        $path = tempnam(sys_get_temp_dir(), 'user-report-');
        if ($path === false) {
            throw new \RuntimeException('Unable to allocate a temporary report file.');
        }

        $zip = new \ZipArchive;
        if ($zip->open($path, \ZipArchive::CREATE | \ZipArchive::OVERWRITE) !== true) {
            @unlink($path);
            throw new \RuntimeException('Unable to create the Excel report archive.');
        }

        $rows = [
            ['User report'],
            ['Generated at', now()->format('Y-m-d H:i:s')],
            ['Generated by', $request->user()?->name ?? ''],
            ['Name', 'Email', 'Department', 'Role', 'Status', 'Created'],
        ];
        foreach ($users as $user) {
            $rows[] = [
                $user->name,
                $user->email,
                $user->department ?? '',
                $user->role ?? '',
                $user->status ?? '',
                $user->created_at?->format('Y-m-d') ?? '',
            ];
        }

        $sheetRows = '';
        foreach ($rows as $rowIndex => $row) {
            $cells = '';
            foreach ($row as $columnIndex => $value) {
                $reference = $this->columnName($columnIndex + 1).($rowIndex + 1);
                $escapedValue = htmlspecialchars((string) $value, ENT_XML1 | ENT_QUOTES, 'UTF-8');
                $cells .= '<c r="'.$reference.'" t="inlineStr"><is><t xml:space="preserve">'.$escapedValue.'</t></is></c>';
            }
            $sheetRows .= '<row r="'.($rowIndex + 1).'">'.$cells.'</row>';
        }

        $zip->addFromString('[Content_Types].xml', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            .'<Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types">'
            .'<Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/>'
            .'<Default Extension="xml" ContentType="application/xml"/>'
            .'<Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/>'
            .'<Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/>'
            .'</Types>');
        $zip->addFromString('_rels/.rels', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            .'<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            .'<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/>'
            .'</Relationships>');
        $zip->addFromString('xl/workbook.xml', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            .'<workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" '
            .'xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets>'
            .'<sheet name="Users" sheetId="1" r:id="rId1"/></sheets></workbook>');
        $zip->addFromString('xl/_rels/workbook.xml.rels', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            .'<Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships">'
            .'<Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/>'
            .'</Relationships>');
        $zip->addFromString('xl/worksheets/sheet1.xml', '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            .'<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><sheetData>'
            .$sheetRows.'</sheetData></worksheet>');
        $zip->close();

        return response()->download($path, 'user-report.xlsx', [
            'Content-Type' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
        ])->deleteFileAfterSend(true);
    }

    private function columnName(int $column): string
    {
        $name = '';
        while ($column > 0) {
            $remainder = ($column - 1) % 26;
            $name = chr(65 + $remainder).$name;
            $column = intdiv($column - 1, 26);
        }

        return $name;
    }

    private function safeCsvCell(?string $value): string
    {
        $value = (string) $value;

        return preg_match('/^\s*[=+\-@]/u', $value) === 1 ? "'".$value : $value;
    }

    private function filteredUsers(Request $request)
    {
        return User::query()
            ->when($request->filled('search'), function ($query) use ($request): void {
                $search = trim((string) $request->string('search'));
                $query->where(function ($query) use ($search): void {
                    $query->where('name', 'like', "%{$search}%")
                        ->orWhere('email', 'like', "%{$search}%")
                        ->orWhere('username', 'like', "%{$search}%");
                });
            })
            ->when($request->filled('department'), fn ($query) => $query->where('department', $request->string('department')))
            ->when($request->filled('role'), fn ($query) => $query->where('role', $request->string('role')))
            ->when($request->filled('status'), fn ($query) => $query->where('status', $request->string('status')))
            ->when($request->filled('from'), fn ($query) => $query->whereDate('created_at', '>=', $request->input('from')))
            ->when($request->filled('to'), fn ($query) => $query->whereDate('created_at', '<=', $request->input('to')))
            ->latest();
    }

    private function filterRules(Request $request): array
    {
        $rules = [
            'search' => ['nullable', 'string', 'max:255'],
            'department' => ['nullable', 'string', 'max:255'],
            'role' => ['nullable', 'string', 'max:100'],
            'status' => ['nullable', 'string', 'max:100'],
            'from' => ['nullable', 'date'],
            'to' => ['nullable', 'date'],
        ];

        if ($request->filled('from') && $request->filled('to')) {
            $rules['to'][] = 'after_or_equal:from';
        }

        return $rules;
    }
}
